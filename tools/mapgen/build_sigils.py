#!/usr/bin/env python3
"""
Builds src/ReplicatedStorage/Shared/Data/World/SigilArt.luau from the house sigils in
tools/mapgen/sigils/<houseId>.py (see sigil_kit.py for the drawing kit and conventions).

Each sigil becomes layers of flat-coloured triangles in a 100 x 120 shield box; the game draws
them with SigilView and the map preview with tools/render_map_preview.py.

Usage:
  python3 tools/mapgen/build_sigils.py [--sheet build/sigils.png] [house ...]
"""

import argparse
import importlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "sigils"))

import sigil_kit  # noqa: E402

OUTPUT = ROOT / "src/ReplicatedStorage/Shared/Data/World/SigilArt.luau"
HOUSES = ["stark", "arryn", "tully", "greyjoy", "lannister", "tyrell", "baratheon", "targaryen", "martell"]

HEADER = """--!strict
--[[
	SigilArt — the great houses' crests as flat vector art. GENERATED by tools/mapgen/build_sigils.py
	from tools/mapgen/sigils/<houseId>.py; edit those and rebuild rather than editing this file.

	Each sigil is a list of layers drawn bottom to top inside a 100 x 120 box (x right, y down):
	the dark rim of a heater shield, the field, then the charge. A layer is one colour and a flat
	list of triangles { x1, y1, x2, y2, x3, y3, ... }. UI/SigilView draws them.
]]

export type Layer = { color: string, tris: { number } }
export type Sigil = { layers: { Layer } }

local SigilArt: { [string]: Sigil } = {
"""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("houses", nargs="*")
    parser.add_argument("--sheet", help="contact sheet PNG of all sigils")
    args = parser.parse_args()
    lines = [HEADER.rstrip("\n")]
    images = []
    total = 0
    for house in HOUSES:
        if not (HERE / "sigils" / f"{house}.py").exists():
            print(f"{house:10} (no art yet: the crest shows a plain shield)")
            continue
        module = importlib.import_module(house)
        layers = sigil_kit.finish(module.build())
        lines.append(f"\t{house} = {{ layers = {{")
        count = 0
        for colour, geom in layers:
            tris = sigil_kit.triangulate(geom)
            count += len(tris)
            flat = ", ".join(f"{x:.1f}, {y:.1f}" for tri in tris for x, y in tri)
            lines.append(f'\t\t{{ color = "{colour}", tris = {{ {flat} }} }},')
        lines.append("\t} },")
        total += count
        print(f"{house:10} {count:4} triangles")
        if args.sheet:
            path = Path(args.sheet).with_name(f"sigil_{house}.png")
            sigil_kit.render(module.build(), path, 240)
            images.append(path)
    lines.append("}")
    lines.append("")
    lines.append("return SigilArt")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"total {total} triangles -> {OUTPUT.relative_to(ROOT)}")
    if args.sheet:
        from PIL import Image

        tiles = [Image.open(p) for p in images]
        w, h = tiles[0].size
        sheet = Image.new("RGB", (w * len(tiles) + 8 * (len(tiles) - 1), h), (61, 74, 99))
        for i, tile in enumerate(tiles):
            sheet.paste(tile, (i * (w + 8), 0))
        sheet.save(args.sheet)
        print(f"wrote {args.sheet}")


if __name__ == "__main__":
    main()
